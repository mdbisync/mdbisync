// A check created with GITHUB_TOKEN has the same App as an Actions job.
// Only the workflow-run and job APIs establish that a job actually ran.
import { message } from '../messages.ts';
import { type GitHubRepository, PullRequestError, request } from './github.ts';

export interface WorkflowIdentity {
  path: string;
  /** Repository blob (inferred for PR runs), or a GitHub-managed workflow id.
   * PR associations are mutable; this is an extra consistency guard, not
   * proof of the workflow revision that executed.
   */
  revision: string;
  event: 'push' | 'pull_request' | 'workflow_dispatch' | 'dynamic';
}

/**
 * A genuine pull request job whose pull request moved on from its head, or
 * closed: GitHub names the current head of each open pull request in a run's
 * association, so the revision the job ran can no longer be inferred. Its file and event are
 * verified like an identity. `standIn` is the blob that file has on the job's
 * head, only when the association's base holds the same blob now, so no base
 * change can be what the job ran instead. Never set for any other reason a
 * revision is unknown (both sides changed the file, another base, an
 * ambiguous association): those stay unverifiable.
 */
export interface MovedJobSource {
  path: string;
  event: 'pull_request';
  standIn?: string;
}

interface WorkflowRun {
  id?: unknown;
  check_suite_id?: unknown;
  head_sha?: unknown;
  path?: unknown;
  event?: unknown;
  workflow_id?: unknown;
  pull_requests?: Array<{ head?: { sha?: unknown }; base?: { sha?: unknown; ref?: unknown; repo?: { url?: unknown } } }>;
  head_repository?: { full_name?: unknown } | null;
}

export interface ActionsJob {
  /** Null when the revision is not known: such a job never passes. */
  workflow: WorkflowIdentity | null;
  /** With a null `workflow`: set only when the job's pull request moved on from its head. */
  moved?: MovedJobSource;
  name: string;
  outcome: 'pending' | 'passed' | 'failed';
}

const PAGE_SIZE = 100;
const MAX_PAGES = 10;
const PASSING = new Set(['success', 'neutral', 'skipped']);
const positive = (value: unknown): value is number => Number.isSafeInteger(value) && (value as number) > 0;

/** Jobs from the given suite on this exact repository head, keyed by check-run id. Unknown evidence never passes. */
export async function actionsJobs(target: GitHubRepository, sha: string, suite: number): Promise<Map<number, ActionsJob>> {
  const jobs = new Map<number, ActionsJob>();
  // A workflow run owns one suite. Ambiguous or truncated evidence cannot
  // establish an identity; do not search an unbounded list of possible runs.
  const answer = await request(target, 'GET', `/actions/runs?check_suite_id=${suite}&head_sha=${sha}&per_page=2`);
  const body = answer.json as { total_count?: unknown; workflow_runs?: unknown } | null;
  if (answer.status !== 200 || !Array.isArray(body?.workflow_runs) || typeof body.total_count !== 'number') {
    throw new PullRequestError(message('github.reading-workflow-runs'), answer.status);
  }
  if (body.total_count !== 1 || body.workflow_runs.length !== 1) return jobs;
  const run = body.workflow_runs[0] as WorkflowRun | null;
  if (!run || !positive(run.id) || run.check_suite_id !== suite || run.head_sha !== sha ||
      typeof run.head_repository?.full_name !== 'string' || run.head_repository.full_name.toLowerCase() !== target.repository.toLowerCase() ||
      typeof run.path !== 'string') return jobs;
  let revision: string | undefined;
  let moved: MovedJobSource | undefined;
  if (run.event === 'dynamic' && ['dynamic/github-code-scanning/codeql', 'dynamic/github-code-quality/codeql'].includes(run.path) && positive(run.workflow_id)) {
    // Managed CodeQL is generated by GitHub, without a repository file.
    // A user-created workflow cannot choose this managed path and event.
    revision = `github-managed:${run.workflow_id}`;
  } else {
    if (!['push', 'pull_request', 'workflow_dispatch'].includes(String(run.event))) return jobs;
    if (run.event === 'pull_request') {
      const inferred = await inferredPullRequestWorkflowRevision(target, sha, run);
      if (typeof inferred === 'object') moved = inferred;
      else revision = inferred;
    } else revision = await workflowRevision(target, sha, run.path);
  }
  const workflow = revision === undefined ? null : { path: run.path, revision, event: run.event as WorkflowIdentity['event'] };
  await readJobs(target, sha, run.id, workflow, moved, jobs);
  return jobs;
}

/** Infer a blob from the reported PR association as a fail-closed consistency guard.
 * The association can change after execution; it is not an execution receipt.
 * Genuine job membership, suite, repository, head and path are verified separately.
 * An association that names another head of the same pull request base (the pull
 * request moved on from this one) gives the job's moved source instead.
 */
async function inferredPullRequestWorkflowRevision(target: GitHubRepository, sha: string, run: WorkflowRun): Promise<string | MovedJobSource | undefined> {
  const api = (target.apiUrl ?? 'https://api.github.com').replace(/\/$/, '');
  const repository = `${api}/repos/${target.repository}`.toLowerCase();
  if (!Array.isArray(run.pull_requests) || run.pull_requests.length > 1) return undefined;
  // No open pull request names the run any more (it closed, or its branch moved): nothing to compare a stand-in with.
  if (run.pull_requests.length === 0) return { path: run.path as string, event: 'pull_request' };
  const pr = run.pull_requests[0];
  const base = pr?.base;
  if (typeof pr?.head?.sha !== 'string' || !/^[0-9a-f]{40,64}$/.test(pr.head.sha) || base?.ref !== (target.baseBranch ?? 'main') ||
      typeof base.sha !== 'string' || !/^[0-9a-f]{40,64}$/.test(base.sha) ||
      typeof base.repo?.url !== 'string' || base.repo.url.toLowerCase() !== repository) return undefined;
  const headRevision = await workflowRevision(target, sha, run.path as string);
  if (pr.head.sha !== sha) {
    const baseRevision = base.sha === sha ? headRevision : await workflowRevision(target, base.sha, run.path as string);
    return { path: run.path as string, event: 'pull_request', ...(headRevision !== undefined && headRevision === baseRevision ? { standIn: headRevision } : {}) };
  }
  if (base.sha === sha) return headRevision;
  const baseRevision = await workflowRevision(target, base.sha, run.path as string);
  if (headRevision === baseRevision) return headRevision;
  const compared = await request(target, 'GET', `/compare/${base.sha}...${sha}`);
  const common = (compared.json as { merge_base_commit?: { sha?: unknown } } | null)?.merge_base_commit?.sha;
  if (compared.status !== 200) throw new PullRequestError(message('github.reading-workflow-revision'), compared.status);
  if (typeof common !== 'string' || !/^[0-9a-f]{40,64}$/.test(common)) return undefined;
  const ancestorRevision = await workflowRevision(target, common, run.path as string);
  // For a one-sided edit Git's merge uses that side's exact blob. If both
  // sides changed the file, do not invent the result of the content merge.
  if (headRevision === ancestorRevision) return baseRevision;
  if (baseRevision === ancestorRevision) return headRevision;
  return undefined;
}

/** A repository workflow's blob on an authenticated head; path components are always URL encoded. */
/** A repository workflow file's path: directly in `.github/workflows/`, a `.yml` or `.yaml` file. */
// eslint-disable-next-line no-control-regex
export const WORKFLOW_FILE = /^\.github\/workflows\/[^/\\\x00-\x1f]+\.ya?ml$/;

export async function workflowRevision(target: GitHubRepository, sha: string, path: string): Promise<string | undefined> {
  if (!WORKFLOW_FILE.test(path)) return undefined;
  const encoded = path.split('/').map(encodeURIComponent).join('/');
  const file = await request(target, 'GET', `/contents/${encoded}?ref=${sha}`);
  const blob = file.json as { type?: unknown; sha?: unknown } | null;
  if (file.status === 404) return undefined;
  if (file.status !== 200) throw new PullRequestError(message('github.reading-workflow-revision'), file.status);
  return blob?.type === 'file' && typeof blob.sha === 'string' && /^[0-9a-f]{40,64}$/.test(blob.sha) ? blob.sha : undefined;
}

async function readJobs(target: GitHubRepository, sha: string, run: number, workflow: WorkflowIdentity | null, moved: MovedJobSource | undefined, jobs: Map<number, ActionsJob>): Promise<void> {
  const api = (target.apiUrl ?? 'https://api.github.com').replace(/\/$/, '');
  const prefix = `${api}/repos/${target.repository}/check-runs/`;
  for (let page = 1; page <= MAX_PAGES; page += 1) {
    const answer = await request(target, 'GET', `/actions/runs/${run}/jobs?filter=latest&per_page=${PAGE_SIZE}&page=${page}`);
    const body = answer.json as { total_count?: unknown; jobs?: unknown } | null;
    if (answer.status !== 200 || !Array.isArray(body?.jobs) || typeof body.total_count !== 'number') {
      throw new PullRequestError(message('github.reading-workflow-jobs'), answer.status);
    }
    for (const job of body.jobs as Array<{ run_id?: unknown; head_sha?: unknown; check_run_url?: unknown; name?: unknown; status?: unknown; conclusion?: unknown }>) {
      if (typeof job.name !== 'string' || job.run_id !== run || job.head_sha !== sha || typeof job.check_run_url !== 'string' || !job.check_run_url.toLowerCase().startsWith(prefix.toLowerCase())) continue;
      const suffix = job.check_run_url.slice(prefix.length);
      if (!/^[1-9][0-9]*$/.test(suffix) || !positive(Number(suffix))) continue;
      const outcome = job.status !== 'completed' ? 'pending' : typeof job.conclusion === 'string' && PASSING.has(job.conclusion) ? 'passed' : 'failed';
      jobs.set(Number(suffix), { workflow, ...(workflow === null && moved !== undefined ? { moved } : {}), name: job.name, outcome });
    }
    if (page * PAGE_SIZE >= body.total_count || body.jobs.length === 0) break;
  }
}
