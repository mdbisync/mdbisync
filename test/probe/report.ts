// Renders a probe run as a Markdown report: the facts the engine depends on,
// one row per construct, and the changes Linear makes to each fixture.

import type { Drift } from './record.ts';
import type { FixtureResult, LimitFact, ProbeRun } from './probe.ts';
import { describeSummary, type YjsNode } from './yjs-summary.ts';

export interface ReportOptions {
  /** Front-matter title, when the report lives in a knowledge base. */
  title?: string | undefined;
  drift: Drift[];
  /** Whether the run wrote its forms as the new record. */
  updated: boolean;
}

const MAX_DIFF_LINES = 12;
const MAX_LINE = 160;

export function renderReport(run: ProbeRun, options: ReportOptions): string {
  const out: string[] = [];
  const date = (run.finishedAt ?? run.startedAt).slice(0, 10);
  if (options.title) out.push('---', `title: ${options.title}`, `updated: ${date}`, 'status: generated', '---', '');
  out.push('# Linear format report', '');
  out.push(
    'Generated by the format probe; do not edit by hand. The probe writes every',
    'synchronized fixture of the bank to a Linear document, reads it back,',
    'writes the readback again and reads again, and decodes the Yjs state',
    'Linear stores. Asset links are uploaded first and mapped back to their',
    'bank paths, so recorded forms do not change from run to run.',
    '',
  );

  const results = run.fixtures;
  const accepted = results.filter((r) => r.first !== undefined);
  const changed = accepted.filter((r) => r.first !== r.source);
  const notFixed = accepted.filter((r) => r.fixedPoint === false);
  const refused = results.filter((r) => r.refused !== undefined);
  out.push('## Run', '');
  out.push('| Item | Value |', '| --- | --- |');
  out.push(`| Run id | \`${run.runId}\` |`);
  out.push(`| Started, finished (UTC) | ${run.startedAt} to ${run.finishedAt ?? 'not finished'} |`);
  out.push(`| Fixtures probed | ${results.length} |`);
  out.push(`| Accepted by Linear | ${accepted.length} |`);
  out.push(`| Refused by Linear | ${refused.length} |`);
  out.push(`| Changed by Linear (form differs from the source) | ${changed.length} |`);
  out.push(`| No fixed point (second readback differs) | ${notFixed.length} |`);
  out.push(`| Yjs state differs after writing the readback back | ${results.filter((r) => r.yjsStable === false).length} |`);
  out.push(`| Yjs state | ${run.yjsBlocked ? `env-blocked: ${cell(run.yjsBlocked)}` : `decoded for ${results.filter((r) => r.yjs).length}`} |`);
  out.push(`| Drift against the recorded forms | ${options.updated ? 'record updated by this run' : String(options.drift.length)} |`);
  out.push(`| API requests | ${requestsLine(run.requests)} |`);
  out.push(`| Cleanup | ${cell(run.cleanup.join('; ') || 'none')} |`);
  out.push('');

  out.push(...renderFacts(run));

  if (!options.updated && options.drift.length > 0) {
    out.push('## Drift', '', '| Fixture | Kind | Detail |', '| --- | --- | --- |');
    for (const drift of options.drift) out.push(`| \`${drift.file}\` | ${drift.kind} | ${cell(drift.detail)} |`);
    out.push('');
  }

  out.push('## Constructs', '');
  out.push(
    '"Changed" compares Linear\'s form with the source; "fixed point" compares',
    'the second readback with the first. "Kept only in Yjs" lists stored',
    'attribute values that Linear\'s Markdown does not show.',
    '',
  );
  out.push('| Fixture | Construct | Class (index) | Changed | Fixed point | Yjs nodes | Kept only in Yjs |');
  out.push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const result of results) {
    const klass = `${result.class}${result.rule ? ` (${result.rule})` : ''}${result.basis === 'assumed' ? ', assumed' : ''}`;
    const changedCell = result.refused !== undefined ? `refused: ${cell(result.refused)}` : result.first === result.source ? 'no' : 'yes';
    const fixed =
      result.fixedPoint === undefined
        ? result.secondRefused
          ? `refused: ${cell(result.secondRefused)}`
          : 'n/a'
        : `${result.fixedPoint ? 'yes' : '**no**'}${result.yjsStable === false ? ' (Yjs differs)' : ''}`;
    const nodes = result.yjs ? cell(describeSummary(result.yjs).join(', ')) : result.yjsError ? cell(result.yjsError) : 'n/a';
    out.push(`| \`${result.file}\` | ${result.construct} | ${klass} | ${changedCell} | ${fixed} | ${nodes} | ${cell(keptOnlyInYjs(result).join(', ') || '')} |`);
  }
  out.push('');

  out.push('## Changes Linear makes', '');
  out.push('Per changed fixture: the first lines that differ (`-` source, `+` Linear\'s form).', '');
  for (const result of changed) {
    out.push(`### ${result.file}`, '');
    out.push(...fenced(diffLines(result.source, result.first ?? '')));
    if (result.fixedPoint === false) {
      out.push('', 'Second round trip (`-` first readback, `+` second):', '');
      out.push(...fenced(diffLines(result.first ?? '', result.second ?? '')));
    }
    out.push('');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

function renderFacts(run: ProbeRun): string[] {
  const facts = run.facts;
  const out: string[] = ['## Facts the engine depends on', '', '| Fact | Measured |', '| --- | --- |'];
  const limit = (fact: LimitFact | undefined) =>
    fact === undefined
      ? 'not measured'
      : fact.refused === undefined
        ? `no refusal up to ${fact.accepted} (${fact.tries} tries)`
        : `${fact.accepted} accepted, ${fact.refused} refused: ${cell(fact.refusal ?? '')} (${fact.tries} tries)`;
  out.push(`| Title length limit (characters) | ${limit(facts.titleLength)} |`);
  out.push(`| Content length limit (characters) | ${limit(facts.contentLength)} |`);
  if (facts.contentUnit) {
    out.push(`| Content over the limit only in UTF-8 bytes (two-byte letters, the limit) | ${cell(facts.contentUnit.utf8BytesOnly)} |`);
    out.push(`| Content over the limit in UTF-16 units and bytes, within it in code points (emoji, half the limit plus one) | ${cell(facts.contentUnit.utf16AndBytes)} |`);
    out.push(`| Content over the limit in every count (emoji, the limit plus one; control) | ${cell(facts.contentUnit.allCounts)} |`);
  }
  for (const upload of facts.uploads ?? []) {
    out.push(`| Upload of ${upload.declaredBytes.toLocaleString('en-US')} bytes (declared size; no bytes sent) | ${cell(upload.outcome)} |`);
  }
  const returned = facts.mutationsReturnStoredContent;
  if (returned) {
    out.push(`| \`documentCreate\` payload equals the stored content | ${returned.create.same} same, ${returned.create.different} different |`);
    out.push(`| \`documentUpdate\` payload equals the stored content | ${returned.update.same} same, ${returned.update.different} different |`);
  }
  for (const [query, outcome] of Object.entries(facts.trashed ?? {})) {
    out.push(`| A trashed document in a query by ${query} | ${outcome} |`);
  }
  if (facts.teamFilterIncludesProjectDocuments !== undefined) {
    out.push(`| A team filter on \`documents\` returns the team's project documents | ${facts.teamFilterIncludesProjectDocuments ? 'yes' : 'no'} |`);
  }
  if (facts.projectDocumentHasTeam !== undefined) {
    out.push(`| A project document's \`team\` field is set | ${facts.projectDocumentHasTeam ? 'yes' : 'no'} |`);
  }
  for (const cost of facts.complexity ?? []) {
    out.push(`| Complexity of ${cost.query}, first ${cost.first} | ${cost.complexity ?? 'no header'}${cost.outcome === 'ok' ? '' : `, ${cell(cost.outcome)}`} |`);
  }
  for (const [name, value] of Object.entries(facts.rateLimitHeaders ?? {})) {
    out.push(`| Header \`${name}\` | ${cell(value)} |`);
  }
  const status = facts.rateLimitStatus as { limits?: Array<{ type: string; allowedAmount: number; period: number }> } | undefined;
  for (const entry of status?.limits ?? []) {
    out.push(`| \`rateLimitStatus\` ${entry.type} | ${entry.allowedAmount} per ${entry.period / 1000} s |`);
  }
  for (const upload of run.uploads) {
    if (upload.outcome !== 'uploaded') out.push(`| Asset upload \`${upload.file}\` | ${cell(upload.outcome)} |`);
  }
  out.push('');
  return out;
}

/** String attribute values in the Yjs state that Linear's Markdown does not contain. */
export function keptOnlyInYjs(result: FixtureResult): string[] {
  if (!result.yjs || result.first === undefined) return [];
  const markdown = result.first;
  const found = new Set<string>();
  const visit = (nodes: YjsNode[]) => {
    for (const node of nodes) {
      if ('text' in node) continue;
      for (const [key, value] of Object.entries(node.attrs ?? {})) {
        if (typeof value === 'string' && value !== '' && !value.startsWith('<') && !markdown.includes(value)) {
          found.add(`${node.type}.${key}=${JSON.stringify(value.length > 40 ? `${value.slice(0, 37)}...` : value)}`);
        } else if (typeof value === 'number' && !['level', 'order', 'colspan', 'rowspan'].includes(key)) {
          found.add(`${node.type}.${key}=${value}`);
        }
      }
      visit(node.children ?? []);
    }
  };
  visit(result.yjs.content);
  return [...found].sort();
}

/** Lines between the common head and tail of two texts, as a short diff. */
export function diffLines(before: string, after: string): string[] {
  const a = before.split('\n');
  const b = after.split('\n');
  let head = 0;
  while (head < a.length && head < b.length && a[head] === b[head]) head += 1;
  let tail = 0;
  while (tail < a.length - head && tail < b.length - head && a[a.length - 1 - tail] === b[b.length - 1 - tail]) tail += 1;
  const removed = a.slice(head, a.length - tail);
  const added = b.slice(head, b.length - tail);
  const lines = [`@@ line ${head + 1} @@`];
  const show = (prefix: string, list: string[]) => {
    for (const line of list.slice(0, MAX_DIFF_LINES)) lines.push(`${prefix}${visible(line)}`);
    if (list.length > MAX_DIFF_LINES) lines.push(`${prefix}... ${list.length - MAX_DIFF_LINES} more lines`);
  };
  show('-', removed);
  show('+', added);
  if (removed.length === 0 && added.length === 0) lines.push(' (only line endings or the final newline differ)');
  return lines;
}

/** Makes invisible differences visible: tabs, carriage returns, trailing spaces. */
function visible(line: string): string {
  const shown = line.replace(/\t/g, '→').replace(/\r/g, '␍').replace(/ +$/, (spaces) => '·'.repeat(spaces.length));
  return shown.length > MAX_LINE ? `${shown.slice(0, MAX_LINE - 3)}...` : shown;
}

function fenced(lines: string[]): string[] {
  const longest = Math.max(2, ...lines.map((line) => Math.max(0, ...[...line.matchAll(/~+/g)].map((m) => m[0].length))));
  const fence = '~'.repeat(longest + 1);
  return [`${fence}diff`, ...lines, fence];
}

function cell(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function requestsLine(requests: unknown): string {
  const stats = requests as { total?: number; storagePuts?: number } | undefined;
  if (!stats || stats.total === undefined) return 'not counted';
  return `${stats.total} (plus ${stats.storagePuts ?? 0} storage uploads)`;
}
