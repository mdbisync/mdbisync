// Converts the JSON that atlas.html dumps into dejavu-atlas.ts, the glyph
// data the demo pictures draw their text with. Run once after atlas.html:
//
//   node test/demo/font/make-atlas.ts <dumped atlas.json.html>

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

type DumpedGlyph = { ch: number; advance: number; left: number; top: number; width: number; height: number; alpha: number[] };
type DumpedFont = { name: string; size: number; ascent: number; descent: number; glyphs: DumpedGlyph[] };

const input = process.argv[2];
if (!input) throw new Error("usage: node test/demo/font/make-atlas.ts <atlas.json.html>");
const html = readFileSync(input, "utf8");
const body = /<body>([\s\S]*)<\/body>/.exec(html)?.[1];
if (!body) throw new Error("no <body> in the dumped page");
const json = body.replaceAll("&quot;", '"').replaceAll("&lt;", "<").replaceAll("&gt;", ">").replaceAll("&amp;", "&");
const fonts = (JSON.parse(json) as { fonts: DumpedFont[] }).fonts;

const lines = [
  "// Generated by make-atlas.ts from atlas.html; do not edit. Glyph bitmaps",
  "// rendered from DejaVu Sans and DejaVu Sans Bold; see LICENSE in this folder.",
  "//",
  "// Each glyph row: code point, advance, left, top (from the baseline), width,",
  "// height. The alpha bytes of all glyphs follow one another in `alpha`",
  "// (deflate, then base64), in the order of the rows.",
  "",
  "export type AtlasFont = { size: number; ascent: number; descent: number; glyphs: readonly (readonly number[])[]; alpha: string };",
  "",
  "export const ATLAS: Record<string, AtlasFont> = {",
];
for (const font of fonts) {
  const alpha = Buffer.from(font.glyphs.flatMap((g) => g.alpha));
  const rows = font.glyphs.map((g) => `[${[g.ch, g.advance, g.left, g.top, g.width, g.height].join(", ")}]`);
  lines.push(`  ${font.name}: {`);
  lines.push(`    size: ${font.size},`);
  lines.push(`    ascent: ${font.ascent},`);
  lines.push(`    descent: ${font.descent},`);
  lines.push("    glyphs: [");
  for (let i = 0; i < rows.length; i += 6) lines.push(`      ${rows.slice(i, i + 6).join(", ")},`);
  lines.push("    ],");
  const encoded = deflateSync(alpha, { level: 9 }).toString("base64");
  lines.push("    alpha:");
  const parts: string[] = [];
  for (let i = 0; i < encoded.length; i += 100) parts.push(`      "${encoded.slice(i, i + 100)}"`);
  lines.push(`${parts.join(" +\n")},`);
  lines.push("  },");
}
lines.push("};", "");
const out = join(dirname(fileURLToPath(import.meta.url)), "dejavu-atlas.ts");
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}`);
