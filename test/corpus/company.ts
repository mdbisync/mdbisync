/** One piece of work a team writes about; templates build sentences around these fields. */
export type Topic = {
  /** A short noun phrase in sentence case, used in titles. */
  title: string;
  /** The service or component the topic is about. */
  system: string;
  /** One sentence: what the change does, for summaries. */
  summary: string;
  /** Why it matters now: the problem with evidence. */
  problem: string;
  /** What the team proposes or did. */
  change: string;
  /** What could go wrong. */
  risk: string;
  /** What is measured, with its unit and the numbers before and after. */
  metric: string;
  unit: string;
  before: number;
  after: number;
};

export type Kind =
  | "rfc" | "design" | "adr" | "runbook" | "postmortem" | "api" | "howto" | "experiment" | "launch" | "policy"
  | "article" | "onboarding" | "faq" | "roadmap" | "meeting" | "status" | "handoff" | "release" | "retro";

